const supportedLanguages = ["es", "ca", "en"];
const pageState = new URLSearchParams(window.location.search);
let language = pageState.get("lang");

if (!supportedLanguages.includes(language)) {
    try {
        language = localStorage.getItem("portfolio-language") || "es";
    } catch {
        language = "es";
    }
}

if (!supportedLanguages.includes(language)) language = "es";

function translated(value) {
    if (language === "es" || !translations[value]) return value;
    return translations[value][language] || value;
}

function translateTextNodes() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);

    nodes.forEach((node) => {
        const value = node.nodeValue;
        const core = value.trim();
        if (!core || !translations[core]) return;
        node.nodeValue = value.replace(core, translated(core));
    });
}

function translateAttributes() {
    document.querySelectorAll("[aria-label], [alt]").forEach((element) => {
        ["aria-label", "alt"].forEach((attribute) => {
            if (!element.hasAttribute(attribute)) return;
            const value = element.getAttribute(attribute);
            element.setAttribute(attribute, translated(value));
        });
    });
}

function preserveLanguageInLinks() {
    document.querySelectorAll("a[href]").forEach((link) => {
        const href = link.getAttribute("href");
        if (!href || href.startsWith("mailto:") || href.startsWith("http") || href.startsWith("#")) return;
        const url = new URL(href, window.location.href);
        if (language === "es") url.searchParams.delete("lang");
        else url.searchParams.set("lang", language);
        link.setAttribute("href", `${url.pathname.split("/").pop()}${url.search}${url.hash}`);
    });
}

function setLanguageControls() {
    document.querySelectorAll(".language-button").forEach((button) => {
        const isCurrent = button.dataset.lang === language;
        button.classList.toggle("is-active", isCurrent);
        if (isCurrent) button.setAttribute("aria-current", "true");
        else button.removeAttribute("aria-current");

        button.addEventListener("click", () => {
            const nextLanguage = button.dataset.lang;
            try {
                localStorage.setItem("portfolio-language", nextLanguage);
            } catch {
                // The URL still preserves the selection when storage is unavailable.
            }
            const url = new URL(window.location.href);
            if (nextLanguage === "es") url.searchParams.delete("lang");
            else url.searchParams.set("lang", nextLanguage);
            window.location.href = url.toString();
        });
    });
}

document.documentElement.lang = language;
document.title = translated(document.title);
translateTextNodes();
translateAttributes();
preserveLanguageInLinks();
setLanguageControls();

const statement = document.getElementById("statement");
const work = document.getElementById("work");
const contact = document.getElementById("contact");
const view = pageState.get("view") || "sara";

if (statement && work && contact) {
    if (view === "work") work.style.display = "block";
    else if (view === "contact") contact.style.display = "block";
    else statement.style.display = "block";
}
